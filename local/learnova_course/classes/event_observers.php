class event_observers {

    /**
     * Drop the activity-scoped discussion when its activity is deleted.
     *
     * These posts only ever had meaning next to that activity, and nothing can
     * reach them once it is gone — so they go with it rather than lingering as
     * rows only the privacy export would ever surface.
     *
     * @param \core\event\course_module_deleted $event
     */
    public static function course_module_deleted(\core\event\course_module_deleted $event): void {
        discussion_manager::delete_module_posts((int) $event->objectid);
    }
}
